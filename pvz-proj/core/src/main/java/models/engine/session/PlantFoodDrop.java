package models.engine.session;

public final class PlantFoodDrop {
    private final double x;
    private final double y;

    public PlantFoodDrop(double x, double y) {
        this.x = x;
        this.y = y;
    }

    public double getX() {
        return x;
    }

    public double getY() {
        return y;
    }
}
